def thick_line(points: Iterable[tuple[float, float]], width: float) -> list[tuple[int, int, float, float]]:
    """Rasterise a polyline: returns (x, y, along 0..1, across -1..1) for covered pixels on a 16x16-ish grid."""
    pts = list(points)
    seglen = [math.dist(pts[i], pts[i + 1]) for i in range(len(pts) - 1)]
    total = sum(seglen)
    out: dict[tuple[int, int], tuple[float, float]] = {}
    xs = [p[0] for p in pts]
    ys = [p[1] for p in pts]
    for y in range(int(min(ys) - width - 1), int(max(ys) + width + 2)):
        for x in range(int(min(xs) - width - 1), int(max(xs) + width + 2)):
            cx, cy = x + 0.5, y + 0.5
            best = None
            acc = 0.0
            for i in range(len(pts) - 1):
                (ax, ay), (bx, by) = pts[i], pts[i + 1]
                vx, vy = bx - ax, by - ay
                l2 = vx * vx + vy * vy
                tt = max(0.0, min(1.0, ((cx - ax) * vx + (cy - ay) * vy) / l2)) if l2 else 0.0
                px, py = ax + vx * tt, ay + vy * tt
                dist = math.hypot(cx - px, cy - py)
                side = math.copysign(1.0, (cx - ax) * vy - (cy - ay) * vx)
                along = (acc + tt * seglen[i]) / total if total else 0.0
                if best is None or dist < best[0]:
                    best = (dist, along, side * dist / (width / 2))
                acc += seglen[i]
            if best and best[0] <= width / 2:
                out[(x, y)] = (best[1], best[2])
    return [(x, y, a, s) for (x, y), (a, s) in out.items()]


def seeded(seed: int) -> random.Random:
    return random.Random(seed)
