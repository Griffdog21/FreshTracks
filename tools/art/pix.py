"""Small pixel-art toolkit for Fresh Tracks textures (Pillow + numpy).

All art in the mod is generated by these scripts so it stays consistent and can be re-made at any time.
Colours are RGBA tuples. Images are numpy uint8 arrays of shape (h, w, 4) until saved.
"""
from __future__ import annotations

import math
import os
import random
from typing import Callable, Iterable, Sequence

import numpy as np
from PIL import Image

RGBA = tuple[int, int, int, int]
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ASSETS = os.path.join(ROOT, "src", "main", "resources", "assets", "freshtracks")


def hexc(s: str, a: int = 255) -> RGBA:
    s = s.lstrip("#")
    return (int(s[0:2], 16), int(s[2:4], 16), int(s[4:6], 16), a)


def canvas(w: int, h: int) -> np.ndarray:
    return np.zeros((h, w, 4), dtype=np.uint8)


def put(img: np.ndarray, x: int, y: int, c: RGBA) -> None:
    h, w = img.shape[:2]
    if 0 <= x < w and 0 <= y < h:
        img[y, x] = c


def get(img: np.ndarray, x: int, y: int) -> RGBA:
    h, w = img.shape[:2]
    if 0 <= x < w and 0 <= y < h:
        return tuple(int(v) for v in img[y, x])
    return (0, 0, 0, 0)


def rect(img: np.ndarray, x0: float, y0: float, x1: float, y1: float, c: RGBA | Callable[[int, int], RGBA]) -> None:
    """Fill [x0, x1) x [y0, y1) (fractional box-UV bounds are floored/ceiled)."""
    for y in range(int(math.floor(y0)), int(math.ceil(y1))):
        for x in range(int(math.floor(x0)), int(math.ceil(x1))):
            put(img, x, y, c(x, y) if callable(c) else c)


def mix(a: RGBA, b: RGBA, t: float) -> RGBA:
    t = max(0.0, min(1.0, t))
    return tuple(int(round(a[i] + (b[i] - a[i]) * t)) for i in range(4))  # type: ignore[return-value]


def shade(c: RGBA, k: float) -> RGBA:
    """k < 0 darkens, k > 0 lightens, -1..1."""
    if k >= 0:
        return mix(c, (255, 255, 255, c[3]), k)
    return mix(c, (0, 0, 0, c[3]), -k)


def hue_shift_dark(c: RGBA, k: float) -> RGBA:
    """Darken toward a cool blue-purple instead of grey (reads nicer in pixel art)."""
    target = (24, 20, 48, c[3])
    return mix(c, target, k)


def outline_inside(img: np.ndarray, strength: float = 0.45) -> np.ndarray:
    """Darken shape pixels that touch transparency on any 4-side: the classic item outline."""
    h, w = img.shape[:2]
    out = img.copy()
    for y in range(h):
        for x in range(w):
            if img[y, x, 3] == 0:
                continue
            edge = False
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if not (0 <= nx < w and 0 <= ny < h) or img[ny, nx, 3] == 0:
                    edge = True
                    break
            if edge:
                out[y, x] = hue_shift_dark(tuple(int(v) for v in img[y, x]), strength)
    return out


def noise2(x: int, y: int, seed: int = 0) -> float:
    """Deterministic hash noise in [0, 1)."""
    n = (x * 374761393 + y * 668265263 + seed * 2147483647) & 0xFFFFFFFF
    n = (n ^ (n >> 13)) * 1274126177 & 0xFFFFFFFF
    return ((n ^ (n >> 16)) & 0xFFFF) / 65536.0


def save(img: np.ndarray, rel: str) -> str:
    path = os.path.join(ASSETS, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    Image.fromarray(img, "RGBA").save(path)
    return path


def upscale_preview(img: np.ndarray, factor: int = 8) -> Image.Image:
    return Image.fromarray(img, "RGBA").resize((img.shape[1] * factor, img.shape[0] * factor), Image.NEAREST)


def contact_sheet(images: Sequence[tuple[str, np.ndarray]], factor: int = 6, cols: int = 6, bg=(40, 44, 60, 255)) -> Image.Image:
    cells = [(name, upscale_preview(im, factor)) for name, im in images]
    cw = max(c.width for _, c in cells) + 8
    ch = max(c.height for _, c in cells) + 8
    rows = (len(cells) + cols - 1) // cols
    sheet = Image.new("RGBA", (cw * cols, ch * rows), bg)
    for i, (_, c) in enumerate(cells):
        sheet.alpha_composite(c, ((i % cols) * cw + 4, (i // cols) * ch + 4))
    return sheet


# ----------------------------------------------------------------------------------------------- box UV

def box_faces(u: float, v: float, w: float, h: float, d: float) -> dict[str, tuple[float, float, float, float]]:
    """Face rectangles (x0, y0, x1, y1) of a Minecraft box-UV cube at (u, v) with size (w, h, d).

    Names are visual for a model drawn with vanilla's flip: 'top' faces the sky, 'front' is the -Z face (toward the
    tips / nose), 'left'/'right' are the +X/-X sides.
    """
    return {
        "top": (u + d, v, u + d + w, v + d),
        "bottom": (u + d + w, v, u + d + 2 * w, v + d),
        "right": (u, v + d, u + d, v + d + h),
        "front": (u + d, v + d, u + d + w, v + d + h),
        "left": (u + d + w, v + d, u + 2 * d + w, v + d + h),
        "back": (u + 2 * d + w, v + d, u + 2 * d + 2 * w, v + d + h),
    }


def paint_box(img: np.ndarray, u: float, v: float, w: float, h: float, d: float,
              painter: Callable[[str, float, float, int, int], RGBA]) -> None:
    """painter(face, s, t, x, y): s across the face (0..1 along its width), t down it (0..1)."""
    for face, (x0, y0, x1, y1) in box_faces(u, v, w, h, d).items():
        fx0, fy0 = int(math.floor(x0)), int(math.floor(y0))
        fx1, fy1 = int(math.ceil(x1)), int(math.ceil(y1))
        fw = max(1, fx1 - fx0)
        fh = max(1, fy1 - fy0)
        for y in range(fy0, fy1):
            for x in range(fx0, fx1):
                s = (x - fx0 + 0.5) / fw
                t = (y - fy0 + 0.5) / fh
                put(img, x, y, painter(face, s, t, x, y))


